<p>
    A little care goes a long way in keeping your flowers fresh and beautiful for longer.
    Here are a few simple tips from our florists.
</p>

<h2>1. Trim the Stems</h2>
<p>
    Cut about 2-3 cm off each stem at a 45&deg; angle before placing your flowers in water.
    This exposes fresh tissue and helps the stem absorb water more easily. Re-trim every
    2-3 days for the best results.
</p>

<h2>2. Change the Water Regularly</h2>
<p>
    Replace the water every 2 days, even if it still looks clean. Bacteria build-up in the
    water is one of the main reasons flowers wilt early. Rinse the vase each time before
    refilling it.
</p>

<h2>3. Remove Leaves Below the Waterline</h2>
<p>
    Any leaves sitting under the water will rot and encourage bacteria growth, which shortens
    your flowers' vase life. Strip off any foliage that would otherwise be submerged.
</p>

<h2>4. Keep Flowers Cool</h2>
<p>
    Display your arrangement away from direct sunlight, heating vents, and ripening fruit
    (fruit releases ethylene gas, which speeds up wilting). A cool spot out of direct sun
    will keep blooms fresher for longer.
</p>

<h2>5. Use Flower Food</h2>
<p>
    If your bouquet came with a flower food sachet, add it to the water as instructed — it
    provides nutrients and helps control bacteria. No sachet? A teaspoon of sugar and a few
    drops of white vinegar in the vase water works as a simple home substitute.
</p>

<h2>6. Know Your Flowers</h2>
<p>
    Some flowers need extra care. Woody stems (like roses) benefit from an angled cut and
    have any thorns removed. Hollow-stemmed flowers (like tulips) prefer cooler water. Bulb
    flowers (like tulips and hyacinths) can be kept in shallower water than other stems.
</p>

